-- Feedback, complaints and improvement ideas sent from the student portal
-- settings dialog. Read by admins only (service role); RLS on with no policies.
create table if not exists public.student_feedback (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students (id) on delete cascade,
  kind text not null check (kind in ('feedback', 'complaint', 'improvement')),
  message text not null,
  created_at timestamptz not null default now()
);

create index if not exists student_feedback_created_idx on public.student_feedback (created_at desc);

alter table public.student_feedback enable row level security;
