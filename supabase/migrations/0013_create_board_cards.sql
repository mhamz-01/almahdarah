-- A student's private kanban board on /student/tasks (To do / In progress / Done).
-- A card points at EITHER one of the student's own tasks (student_tasks) OR a
-- teacher-set task (tasks) — the student chooses what goes on their board.
-- Board status is per student and private; teacher tasks themselves stay
-- global and untouched. Accessed only via /api/student/board with the
-- service role key, so RLS is enabled with deliberately NO anon policy.
-- Run this once in the Supabase SQL Editor (or via `supabase db push`).

create table if not exists public.board_cards (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students (id) on delete cascade,
  personal_task_id bigint references public.student_tasks (id) on delete cascade,
  assigned_task_id bigint references public.tasks (id) on delete cascade,
  status text not null default 'todo' check (status in ('todo', 'in_progress', 'done')),
  created_at timestamptz not null default now(),
  moved_at timestamptz not null default now(),
  constraint board_cards_one_source check ((personal_task_id is null) <> (assigned_task_id is null))
);

create unique index if not exists board_cards_personal_uidx
  on public.board_cards (student_id, personal_task_id) where personal_task_id is not null;
create unique index if not exists board_cards_assigned_uidx
  on public.board_cards (student_id, assigned_task_id) where assigned_task_id is not null;
create index if not exists board_cards_student_idx on public.board_cards (student_id, status, moved_at desc);

alter table public.board_cards enable row level security;
