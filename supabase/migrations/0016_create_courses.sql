-- Courses shown on /student/courses. Lessons are YouTube videos embedded in the
-- portal through the IFrame Player API; only the video id is stored.
-- Reads/writes go through the service role (student pages + /api/student/courses),
-- so RLS is enabled with deliberately NO anon policy.

create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  title text not null,
  description text not null default '',
  instructor text not null default '',
  youtube_playlist_id text unique,
  thumbnail_url text,
  sort_order int not null default 0,
  published boolean not null default true
);

create table if not exists public.course_lessons (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses (id) on delete cascade,
  position int not null,
  title text not null,
  youtube_video_id text not null,
  unique (course_id, position)
);

create index if not exists course_lessons_course_idx on public.course_lessons (course_id, position);

create table if not exists public.lesson_progress (
  student_id bigint not null references public.students (id) on delete cascade,
  lesson_id bigint not null references public.course_lessons (id) on delete cascade,
  last_position_seconds int not null default 0,
  completed boolean not null default false,
  updated_at timestamptz not null default now(),
  primary key (student_id, lesson_id)
);

alter table public.courses enable row level security;
alter table public.course_lessons enable row level security;
alter table public.lesson_progress enable row level security;

