-- Personal to-dos a student creates for themselves on /student/tasks.
-- Unlike public.tasks (set by teachers for everyone), these are private to
-- one student. All reads/writes go through /api/student/tasks and the
-- student tasks page using the service role key, scoped to the signed-in
-- student's id — so RLS is enabled with deliberately NO anon policy.
-- Run this once in the Supabase SQL Editor (or via `supabase db push`).

create table if not exists public.student_tasks (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students (id) on delete cascade,
  created_at timestamptz not null default now(),
  subject text,
  title text not null,
  description text not null default '',
  due_date date,
  completed boolean not null default false,
  -- [{ "url": "...", "name": "...", "path": "..." }]
  attachments jsonb not null default '[]'::jsonb
);

create index if not exists student_tasks_student_idx on public.student_tasks (student_id, created_at desc);

alter table public.student_tasks enable row level security;

-- Public bucket (paths are namespaced by student id and timestamped), same
-- approach as task-attachments. Writes only happen via the service role.
insert into storage.buckets (id, name, public)
values ('student-task-files', 'student-task-files', true)
on conflict (id) do nothing;

drop policy if exists "Public read of student task files" on storage.objects;
create policy "Public read of student task files"
  on storage.objects
  for select
  to public
  using (bucket_id = 'student-task-files');
