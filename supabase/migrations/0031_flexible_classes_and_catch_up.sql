-- Flexible weekly classes, per-date cancellations and catch-up recordings.
--
-- Before this, a streak assumed a class every weekday (Mon–Fri) and "cancelled"
-- was a flag on the weekly timetable row, so it stayed cancelled every week
-- until someone switched it back. Now:
--
--   class_schedule.active_from   a timetable row only counts from this date, so
--                                adding a class never turns past weeks into misses.
--   class_schedule.course_id     the course whose YouTube playlist holds this
--                                class's recordings. Optional: when empty, the
--                                course is guessed from the class name.
--   class_cancellations          one row per cancelled DATE. A cancelled class is
--                                left out of that week's streak target.
--   class_recordings             links a held class date to its uploaded lesson.
--                                Filled automatically by the nightly course sync;
--                                the admin can change it. A student who missed the
--                                class keeps their streak by watching the whole
--                                lesson within 7 days of it being linked.
--   lesson_progress.completed_at when a lesson was first finished (the catch-up
--                                deadline is checked against it).
--
-- Run this once in the Supabase SQL Editor (or via `supabase db push`).

-- Existing rows have always been on the timetable; rows added from now on count from the day they are added.
do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'class_schedule' and column_name = 'active_from'
  ) then
    alter table public.class_schedule add column active_from date not null default '2000-01-01';
    alter table public.class_schedule alter column active_from set default current_date;
  end if;
end $$;

alter table public.class_schedule
  add column if not exists course_id bigint references public.courses (id) on delete set null;

create table if not exists public.class_cancellations (
  id bigint generated by default as identity primary key,
  class_date date not null unique,
  schedule_id bigint references public.class_schedule (id) on delete set null,
  reason text not null default 'Teacher unavailable',
  note text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists class_cancellations_date_idx on public.class_cancellations (class_date desc);

create table if not exists public.class_recordings (
  id bigint generated by default as identity primary key,
  class_date date not null unique,
  schedule_id bigint references public.class_schedule (id) on delete set null,
  lesson_id bigint not null references public.course_lessons (id) on delete cascade,
  -- 'auto' = linked by the nightly sync, 'admin' = chosen by hand (never replaced automatically)
  source text not null default 'auto' check (source in ('auto', 'admin')),
  linked_at timestamptz not null default now(),
  notified_at timestamptz
);

create index if not exists class_recordings_lesson_idx on public.class_recordings (lesson_id);

alter table public.lesson_progress add column if not exists completed_at timestamptz;
update public.lesson_progress set completed_at = updated_at where completed and completed_at is null;

-- Remembers which catch-up reminder emails went out, so a retried cron never sends twice.
alter table public.student_email_prefs add column if not exists last_catch_up_sent_on date;

-- A row that is cancelled right now becomes a cancellation of this week's date
-- for that weekday, and the row itself goes back to normal.
insert into public.class_cancellations (class_date, schedule_id, reason, note)
select
  date_trunc('week', current_date)::date
    + (array_position(array['Monday','Tuesday','Wednesday','Thursday','Friday'], s.day) - 1),
  s.id,
  'Other',
  s.note
from public.class_schedule s
where s.status = 'cancelled'
on conflict (class_date) do nothing;

update public.class_schedule set status = 'scheduled' where status <> 'scheduled';

-- Service role only, like the rest of the portal data.
alter table public.class_cancellations enable row level security;
alter table public.class_recordings enable row level security;
