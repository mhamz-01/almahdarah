-- 1. Students no longer have a level — keep the column for existing rows but
--    make it optional so new students can be created without one.
alter table public.students alter column level drop not null;

-- 2. Admin-set passwords the admin can view/edit later. password_hash (scrypt)
--    is still what the login route verifies; password_enc is the same password
--    AES-256-GCM encrypted by the server (see lib/secret-box.ts) purely so the
--    admin panel can show it back. NULL for logins created before this change.
alter table public.students add column if not exists password_enc text;

-- 3. Public "request access" submissions from /student/request-access, reviewed
--    in /admin/students. Written/read only via the service role key (the
--    password fields never leave the server unencrypted), so RLS is enabled
--    with deliberately NO anon policy.
--    Accepting a request creates the students row (copying the hash/enc), which
--    is what lets that person sign in. Pending/rejected requests cannot sign in.
create table if not exists public.student_requests (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  username text not null,
  password_hash text not null,
  password_enc text not null,
  time_at_almahdrah text not null,
  expectations text not null,
  status text not null default 'pending' check (status in ('pending', 'accepted', 'rejected')),
  reviewed_at timestamptz,
  student_id bigint references public.students (id) on delete set null
);

create index if not exists student_requests_status_idx on public.student_requests (status, created_at desc);
-- At most one open request per username.
create unique index if not exists student_requests_pending_username_uidx
  on public.student_requests (username) where status = 'pending';

alter table public.student_requests enable row level security;
