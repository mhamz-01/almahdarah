-- Self-service "Forgot password?" for the student portal (/student/forgot-password).
--
-- Flow: the student enters their account email -> a 6-digit code is emailed ->
-- entering the right code yields a short-lived, single-use reset token -> the
-- token sets a new password. See lib/password-reset.ts for the limits.
--
-- One row per code request. Rows are written for every request, including
-- emails with no account (code_hash is then NULL and nothing is sent), so the
-- rate limits behave identically either way and never reveal whether an email
-- is registered. Only hashes are stored: code_hash is an HMAC keyed with a
-- server secret, reset_token_hash a SHA-256 of a 256-bit random token.
--
-- Run this once in the Supabase SQL Editor before deploying the feature.

create table if not exists public.student_password_resets (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  email text not null,
  ip text,
  code_hash text,
  expires_at timestamptz not null,
  attempts smallint not null default 0,
  verified_at timestamptz,
  reset_token_hash text unique,
  used_at timestamptz
);

create index if not exists student_password_resets_email_idx on public.student_password_resets (email, created_at desc);
create index if not exists student_password_resets_ip_idx on public.student_password_resets (ip, created_at desc);

-- Read and written only through the service role (the password-reset API routes).
alter table public.student_password_resets enable row level security;

-- Sessions issued before this moment are rejected (lib/get-student-session.ts),
-- so a password reset signs the account out on every other device.
alter table public.students add column if not exists password_changed_at timestamptz;

-- Reset lookups match on the exact lowercased email.
update public.students set email = lower(trim(email)) where email is not null and email <> lower(trim(email));
create index if not exists students_email_idx on public.students (email);
